-- Holds players who appeared on a demo side that had no clan tag set (a
-- generic "Team 1"/"Team 2" placeholder) and had no existing TEAM_MEMBERS
-- roster to fall back to. MATCH_STATS.TEAMNAME is left NULL for these rows
-- until a human resolves which real team the side belongs to.
CREATE TABLE IF NOT EXISTS UNASSIGNED_MATCH_PLAYERS (
    MATCHID INT NOT NULL,
    PLAYERID BIGINT NOT NULL,
    SIDE_INDEX TINYINT NOT NULL,
    DEFAULT_TEAM_NAME VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MATCHID, PLAYERID),
    FOREIGN KEY (MATCHID) REFERENCES MATCHES(MATCHID) ON DELETE CASCADE,
    FOREIGN KEY (PLAYERID) REFERENCES PLAYERS(PLAYERID) ON DELETE CASCADE
);