CREATE TABLE IF NOT EXISTS TEAMS (
    TEAMNAME VARCHAR(255) PRIMARY KEY,
    TEAM_LOGO_URL VARCHAR(512) DEFAULT NULL,
    DESCRIPTION TEXT DEFAULT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS SEASONS (
    SEASON_ID INT NOT NULL AUTO_INCREMENT,
    TEAMNAME VARCHAR(255) NOT NULL,
    NAME VARCHAR(100) NOT NULL,          -- "Spring 2025", "ESL Qualifier", etc.
    START_DATE DATE DEFAULT NULL,
    END_DATE DATE DEFAULT NULL,
    NOTES TEXT DEFAULT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (SEASON_ID),
    CONSTRAINT FK_Season_Team
        FOREIGN KEY (TEAMNAME) REFERENCES TEAMS(TEAMNAME)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE IF NOT EXISTS MATCHES (
    MATCHID int AUTO_INCREMENT PRIMARY KEY ,
    DEMO_NAME varchar(255) NOT NULL ,
    MAP varchar(15) NOT NULL,
    SAVED_DATE varchar(10),
    PARSED_STATS BOOLEAN,
    PARSED_2D BOOLEAN,
    -- Team A Info
    TEAM_A_NAME VARCHAR(255),
    TEAM_A_T_SCORE INT DEFAULT 0,
    TEAM_A_CT_SCORE INT DEFAULT 0,
    TEAM_A_FINAL_SCORE INT DEFAULT 0,

    -- Team B Info
    TEAM_B_NAME VARCHAR(255),
    TEAM_B_T_SCORE INT DEFAULT 0,
    TEAM_B_CT_SCORE INT DEFAULT 0,
    TEAM_B_FINAL_SCORE INT DEFAULT 0,

    SEASON VARCHAR(100) DEFAULT NULL,
    SEASON_ID INT DEFAULT NULL,
    MATCH_DATE DATE DEFAULT NULL,
    NOTES TEXT DEFAULT NULL,
    CONSTRAINT FK_Match_TeamA
        FOREIGN KEY (TEAM_A_NAME) REFERENCES TEAMS(TEAMNAME)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT FK_Match_TeamB
        FOREIGN KEY (TEAM_B_NAME) REFERENCES TEAMS(TEAMNAME)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT FK_Match_Season
        FOREIGN KEY (SEASON_ID) REFERENCES SEASONS(SEASON_ID)
        ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS ROUNDS (
    MATCHID INT NOT NULL,
    ROUND_NO INT NOT NULL,
    WINNING_SIDE INT DEFAULT NULL,
    WIN_REASON INT DEFAULT NULL,
    BOMB_PLANT BOOLEAN DEFAULT 0,
    BOMB_DEFUSE BOOLEAN DEFAULT 0,
    BOMB_EXPLODE BOOLEAN DEFAULT 0,
    SITE CHAR(1) DEFAULT NULL,
    PLANTER_PLAYERID BIGINT DEFAULT NULL,
    DEFUSER_PLAYERID BIGINT DEFAULT NULL,
    OPENING_KILL_SECONDS FLOAT DEFAULT NULL,
    BUY_TYPE_CT TINYINT DEFAULT 0,
    BUY_TYPE_T TINYINT DEFAULT 0,
    T_TEAM VARCHAR(255) DEFAULT NULL,
    CT_TEAM VARCHAR(255) DEFAULT NULL,
    PRIMARY KEY (MATCHID, ROUND_NO), 
    CONSTRAINT FK_Match_Rounds 
        FOREIGN KEY (MATCHID) REFERENCES MATCHES(MATCHID) 
        ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS PLAYERS (
    PLAYERID BIGINT PRIMARY KEY,
    PLAYERNAME VARCHAR(100) NOT NULL UNIQUE,
    ROLE VARCHAR(50) DEFAULT NULL,
    BIO TEXT DEFAULT NULL,
    AVATAR_URL VARCHAR(512) DEFAULT NULL,
    AVATAR_URL_FULL VARCHAR(512) DEFAULT NULL
);
CREATE TABLE IF NOT EXISTS TEAM_MEMBERS (
    PLAYERID BIGINT NOT NULL,
    TEAMNAME VARCHAR(255) NOT NULL,
    ROLE VARCHAR(50) DEFAULT NULL,
    IS_ACTIVE BOOLEAN DEFAULT 1,
    JOINED_AT DATE DEFAULT NULL,
    ROSTER_ORDER INT DEFAULT 0,
    PRIMARY KEY (PLAYERID, TEAMNAME),
    FOREIGN KEY (PLAYERID) REFERENCES PLAYERS(PLAYERID) ON DELETE CASCADE,
    CONSTRAINT FK_Member_Team
        FOREIGN KEY (TEAMNAME) REFERENCES TEAMS(TEAMNAME)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE IF NOT EXISTS TEAM_INVITES (
  INVITE_ID INT NOT NULL AUTO_INCREMENT,
  TEAMNAME VARCHAR(255) NOT NULL,
  STEAM_ID VARCHAR(20) NOT NULL,
  INVITED_BY BIGINT NOT NULL,
  STATUS ENUM('pending', 'accepted', 'declined') DEFAULT 'pending',
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (INVITE_ID),
  CONSTRAINT FK_Invite_Team
      FOREIGN KEY (TEAMNAME) REFERENCES TEAMS(TEAMNAME)
      ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE IF NOT EXISTS TEAM_MODERATORS (
    TEAMNAME VARCHAR(255) NOT NULL,
    PLAYERID BIGINT NOT NULL,
    GRANTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (TEAMNAME, PLAYERID),
    CONSTRAINT FK_Moderator_Team
        FOREIGN KEY (TEAMNAME) REFERENCES TEAMS(TEAMNAME)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (PLAYERID) REFERENCES PLAYERS(PLAYERID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS MATCH_STATS (
    MATCHID INT NOT NULL,
    PLAYERID BIGINT NOT NULL,
    TOTAL_KILLS INT DEFAULT 0,
    TOTAL_DEATHS INT DEFAULT 0,
    TOTAL_ASSISTS INT DEFAULT 0,
    TOTAL_DAMAGE INT DEFAULT 0,
    HEADSHOTS INT DEFAULT 0,
    ENTRY_KILLS INT DEFAULT 0,
    ENTRY_DEATHS INT DEFAULT 0,
    UTILITY_DAMAGE INT DEFAULT 0,
    ONE_KILL_COUNT INT DEFAULT 0,
    TWO_KILL_COUNT INT DEFAULT 0,
    THREE_KILL_COUNT INT DEFAULT 0,
    FOUR_KILL_COUNT INT DEFAULT 0,
    FIVE_KILL_COUNT INT DEFAULT 0,
    TRADED_KILLS INT DEFAULT 0,
    TRADED_DEATHS INT DEFAULT 0,
    CLUTCHES_WON INT DEFAULT 0,
    CLUTCHES_COUNT INT DEFAULT 0,
    FLASH_ASSISTS INT DEFAULT 0,
    TEAM_FLASHES INT DEFAULT 0,
    ENEMIES_FLASHED INT DEFAULT 0,
    HE_DAMAGE INT DEFAULT 0,
    FIRE_DAMAGE INT DEFAULT 0,
    TEAMNAME VARCHAR(255) NULL DEFAULT NULL,
    -- Which physical demo side (0/1, matching MATCHES.TEAM_A_NAME/TEAM_B_NAME)
    -- this player was actually on in this match. TEAMNAME may legitimately
    -- differ from either match-level name (roster override, still-unassigned
    -- NULL), so anything bucketing players into "team A vs team B" for this
    -- match must key off SIDE_INDEX, not off matching TEAMNAME strings.
    SIDE_INDEX TINYINT NULL DEFAULT NULL,
    PRIMARY KEY (MATCHID, PLAYERID),
    CONSTRAINT FK_Stats_Match FOREIGN KEY (MATCHID) 
        REFERENCES MATCHES(MATCHID) ON DELETE CASCADE,
    CONSTRAINT FK_Stats_Player FOREIGN KEY (PLAYERID) 
        REFERENCES PLAYERS(PLAYERID) ON DELETE CASCADE,
    CONSTRAINT FK_Stats_Team FOREIGN KEY (TEAMNAME)
        REFERENCES TEAMS(TEAMNAME) ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE TABLE IF NOT EXISTS ROUND_PARTICIPANTS (
    MATCHID INT NOT NULL,
    ROUND_NO INT NOT NULL,
    PLAYERID BIGINT NOT NULL,
    SIDE INT,
    KILLS INT DEFAULT 0,
    DAMAGE INT DEFAULT 0,
    GOT_KILL BOOLEAN DEFAULT 0,
    GOT_ASSIST BOOLEAN DEFAULT 0,
    GOT_TRADED BOOLEAN DEFAULT 0,
    TRADE_OPPORTUNITY BOOLEAN DEFAULT 0,
    FIRST_KILL BOOLEAN DEFAULT 0,
    FIRST_DEATH BOOLEAN DEFAULT 0,
    SURVIVED BOOLEAN DEFAULT 0,
    PRIMARY KEY (MATCHID, ROUND_NO, PLAYERID),
    FOREIGN KEY (MATCHID, ROUND_NO) REFERENCES ROUNDS(MATCHID, ROUND_NO) ON DELETE CASCADE,
    FOREIGN KEY (PLAYERID) REFERENCES PLAYERS(PLAYERID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS CLUTCHES (
